import StyleDictionary from 'style-dictionary';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// ADR-0010: tokens.json is the single source; the output is generated, never edited by hand.
// Tailwind 4 (CSS-first `@theme`) is pinned; mapping token category -> Tailwind namespace:
//   color.*            -> --color-*      (bg-primary, text-text-muted)
//   space.*, size.control-height/avatar/icon -> --spacing-*  (p-md, h-control, size-icon)
//   size.*-max         -> --container-*  (max-w-content, max-w-form, max-w-modal)
//   radius.*           -> --radius-*     (rounded-button)
//   font.size-*        -> --text-*       (text-small), font.weight-* -> --font-weight-* (font-bold)
//   font.family        -> --font-sans
//   breakpoint.desktop -> --breakpoint-desktop (desktop:)
// Default Tailwind scales are reset so only tokens exist.
const varName = (token) => token.path.join('-');

function mapping(token) {
  const [cat, ...rest] = token.path;
  const key = rest.join('-');
  if (cat === 'color') return `--color-${key}`;
  if (cat === 'space') return `--spacing-${key}`;
  if (cat === 'radius') return `--radius-${key}`;
  if (cat === 'breakpoint') return `--breakpoint-${key}`;
  if (cat === 'size') {
    if (key.endsWith('-max')) return `--container-${key.slice(0, -4)}`;
    return `--spacing-${key.replace(/^control-height$/, 'control')}`;
  }
  if (cat === 'font') {
    if (key === 'family') return '--font-sans';
    if (key.startsWith('size-')) return `--text-${key.slice(5)}`;
    if (key.startsWith('weight-')) return `--font-weight-${key.slice(7)}`;
  }
  return null; // border.*, font.line-height: plain variables in :root
}

const RESETS = [
  '--color-*: initial;',
  '--spacing: initial;',
  '--spacing-*: initial;',
  '--radius-*: initial;',
  '--breakpoint-*: initial;',
  '--container-*: initial;',
  '--text-*: initial;',
  '--font-weight-*: initial;',
  '--font-*: initial;',
  '--shadow-*: initial;',
];

function cssFormat({ dictionary }) {
  // Theme holds the concrete values (`@theme static` emits every variable, used or not);
  // `:root` keeps the mockup names (--space-md...) as aliases, and tokens outside Tailwind.
  const theme = [];
  const root = [];
  for (const t of dictionary.allTokens) {
    const value = t.$value ?? t.value;
    const m = mapping(t);
    if (!m) {
      root.push(`  --${varName(t)}: ${value};`);
      continue;
    }
    theme.push(`  ${m}: ${value};`);
    if (m !== `--${varName(t)}`) root.push(`  --${varName(t)}: var(${m});`);
    if (t.path[0] === 'font' && t.path[1]?.startsWith('size-')) {
      theme.push(`  --text-${t.path[1].slice(5)}--line-height: var(--font-line-height);`);
    }
  }
  return [
    '/* Generated by `pnpm tokens:build` from docs/design/tokens.json. Do not edit. */',
    '@theme static {',
    ...RESETS.map((r) => `  ${r}`),
    ...theme,
    '}',
    '',
    ':root {',
    ...root,
    '}',
    '',
  ].join('\n');
}

/** Builds the CSS file (variables + Tailwind theme) from a tokens.json path. */
export async function buildTokens({ input, output }) {
  const sd = new StyleDictionary({
    source: [input],
    log: { verbosity: 'silent' },
    hooks: { formats: { 'creno/css': cssFormat } },
    platforms: {
      css: { transformGroup: 'css', files: [{ destination: 'tokens.css', format: 'creno/css' }] },
    },
  });
  const files = await sd.formatPlatform('css');
  const content = files[0].output;
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, content);
  return content;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await buildTokens({
    input: fileURLToPath(new URL('../../../docs/design/tokens.json', import.meta.url)),
    output: fileURLToPath(new URL('../generated/tokens.css', import.meta.url)),
  });
}
